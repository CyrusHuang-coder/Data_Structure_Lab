import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1480,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('heading',{name:'让每一步，都看得明白.'}).waitFor({timeout:20000});
await mkdir('../../artifacts',{recursive:true});
await page.screenshot({path:'../../artifacts/dashboard.png',fullPage:true});
await page.goto('http://127.0.0.1:5173/#/workbench/list-insert');
await page.getByRole('button',{name:'运行代码',exact:true}).waitFor();
await page.getByRole('button',{name:'运行代码',exact:true}).click();
await page.getByText('执行完成',{exact:true}).waitFor({timeout:60000});
await page.getByRole('button',{name:'跳到结尾',exact:true}).click();
await page.getByRole('button',{name:'结构检查',exact:true}).click();
await page.getByText('当前已登记对象的结构规则通过。',{exact:false}).waitFor();
await page.screenshot({path:'../../artifacts/workbench.png',fullPage:true});
await page.getByRole('button',{name:'提交测试',exact:false}).click();
await page.getByText('本站测试全部通过',{exact:false}).waitFor({timeout:30000});
console.log(JSON.stringify({errors,url:page.url(),bodyOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),result:'browser smoke passed'},null,2));
await browser.close();
if(errors.length)process.exitCode=1;
